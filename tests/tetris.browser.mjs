import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.GAME_BASE_URL || 'http://127.0.0.1:7100/';
assert.ok(['localhost','127.0.0.1'].includes(new URL(base).hostname));
const browser = await chromium.launch({headless:true});
const errors = [];
try {
  const page = await browser.newPage({ viewport: {width:1280,height:1000}, reducedMotion:'reduce' });
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/api/**', route => route.fulfill({contentType:'application/json',body:JSON.stringify({user:null})}));
  await page.goto(`${base}#tetris`);
  const grid = page.locator('.tetris-grid');
  const activeCells = () => grid.locator('[data-kind="active"]').evaluateAll(elements => elements.map(el => [...el.parentNode.children].indexOf(el)));
  await page.locator('#tetrisStart').waitFor();
  assert.equal(await grid.locator('.tetris-cell').count(), 200);
  assert.equal(await grid.getAttribute('data-phase'), 'ready');
  await page.locator('#tetrisStart').click();
  assert.equal(await grid.getAttribute('data-phase'), 'playing');
  const before = await activeCells();
  await page.keyboard.press('ArrowLeft');
  assert.deepEqual(await activeCells(), before.map(i => i - 1));
  await page.keyboard.press('c');
  assert.ok(await page.locator('#tetrisHold').getAttribute('data-type'));
  assert.equal(await page.locator('[data-tetris="hold"]').isDisabled(), true);
  await page.keyboard.press('Space');
  assert.equal(await grid.locator('[data-kind="locked"]').count(), 4);
  assert.ok(Number(await page.locator('#tetrisScore').textContent()) > 0);
  assert.equal(await page.locator('[data-tetris="hold"]').isDisabled(), false);
  await page.keyboard.press('p');
  const frozen = await activeCells();
  await page.waitForTimeout(1100);
  assert.deepEqual(await activeCells(), frozen);
  assert.equal(await grid.getAttribute('data-phase'), 'paused');
  await page.locator('#tetrisStart').click();
  await page.locator('#howToButton').click();
  await page.waitForFunction(() => document.querySelector('.tetris-grid').dataset.phase === 'paused');
  await page.keyboard.press('Escape');
  assert.equal(await grid.getAttribute('data-phase'), 'paused');
  await page.locator('#tetrisStart').click();
  // Real input stacks pieces until the round ends, then checks local history.
  for (let i = 0; i < 30 && await grid.getAttribute('data-phase') !== 'over'; i++) await page.keyboard.press('Space');
  await page.locator('#victoryModal[open]').waitFor();
  assert.match(await page.locator('#victorySummary').textContent(), /消除.*行/);
  const finalScore = await page.locator('#tetrisScore').textContent();
  await page.locator('[data-close-result]').click();
  await page.locator('#statsButton').click();
  assert.match(await page.locator('#statsBestList').textContent(), /俄罗斯方块/);
  assert.match(await page.locator('#statsBestList').textContent(), new RegExp(`${finalScore} 分`));
  await page.keyboard.press('Escape');
  await page.locator('#tetrisNew').click();
  assert.equal(await page.locator('#tetrisScore').textContent(), '0');
  assert.equal(await grid.locator('[data-kind="locked"]').count(), 0);
  assert.equal(await grid.getAttribute('data-phase'), 'ready');
  await page.locator('#tetrisStart').click();
  // Switch through the actual picker to exercise unmount and listener cleanup.
  await page.locator('#gamePickerButton').click();
  await page.locator('#gameSearch').fill('2048');
  await page.locator('#gameLibrary [data-game="2048"]').click();
  await page.locator('.tiles-grid').waitFor();
  await page.keyboard.press('ArrowLeft');
  await page.locator('#gamePickerButton').click();
  await page.locator('#gameSearch').fill('俄罗斯');
  assert.equal(await page.locator('#gameLibrary button').count(), 1);
  await page.locator('#gameLibrary [data-game="tetris"]').click();
  await page.locator('#tetrisStart').click();
  const remounted = await activeCells();
  await page.keyboard.press('ArrowLeft');
  assert.deepEqual(await activeCells(), remounted.map(i => i - 1));
  await page.locator('[data-tetris="drop"]').click();
  const controls = await page.locator('.tetris-controls button').first().boundingBox();
  assert.ok(controls.width < 150, 'desktop controls share one row');
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({path:'/tmp/gejian-tetris-desktop.png',fullPage:true});
  // Touch layout at a narrow phone width, including continuous movement.
  const mobile = await browser.newPage({viewport:{width:375,height:812},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.route('**/api/**', route => route.fulfill({contentType:'application/json',body:'{"user":null}'}));
  await mobile.goto(`${base}#tetris`);
  await mobile.locator('#tetrisStart').tap();
  await mobile.locator('[data-tetris="rotate"]').tap();
  await mobile.locator('[data-tetris="drop"]').tap();
  assert.equal(await mobile.locator('.tetris-grid [data-kind="locked"]').count(), 4);
  const left = mobile.locator('[data-tetris="left"]');
  await left.scrollIntoViewIfNeeded();
  const box = await left.boundingBox();
  await mobile.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await mobile.mouse.down(); await mobile.waitForTimeout(500); await mobile.mouse.up();
  const xs = await mobile.locator('.tetris-grid [data-kind="active"]').evaluateAll(els => els.map(el => [...el.parentNode.children].indexOf(el) % 10));
  assert.equal(Math.min(...xs), 0, 'holding left reaches the wall');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mobile.locator('[data-tetris="pause"]').tap();
  await mobile.evaluate(() => scrollTo(0, 0));
  await mobile.screenshot({path:'/tmp/gejian-tetris-mobile.png',fullPage:true});
  await mobile.evaluate(() => document.documentElement.dataset.theme = 'dark');
  await mobile.screenshot({path:'/tmp/gejian-tetris-dark.png',fullPage:true});
  assert.deepEqual(errors, []);
  console.log('PASS: Tetris keyboard, touch/hold, pause/dialogs, scoring, local history, reset, switch/remount, phone layout');
} finally { await browser.close(); }
